"""경부선 영등포 남쪽: HGIS 미완성 선형(todo)을 지금 선로 모양으로 바꾼다 (v1.1, 2026-11-27).

python3 gyeongbu_osm.py <page data.json>

- HGIS 철도망의 경부선 영등포 남쪽은 「(todo)」로 표시된 거친 선(11조각, 꼭짓점 87개)뿐이다.
- 같은 data.json의 전철 선로(dedges, metroscope 정리본·OSM) 가운데 1호선의 경부선 구간을 골라
  개통일(1905-01-01)부터 국철로 그린다.
- 고른 근거(이 스크립트를 처음 돌릴 때 잰 값): HGIS 미완성 선형의 꼭짓점 87개 가운데 절반이
  지금 선로에서 28m 안, 90%가 94m 안이다. 300m 넘게 떨어진 4개는 모두 병점–오산 사이(북위 37.19도 부근)에서
  지금 본선보다 1.0–1.2km 동쪽이다. 거리로만 고르면 그 구간에서 서동탄 지선이 뽑혀서, 구간은 끝점 좌표로 직접 정했다.
- 빼는 것: 금천구청–광명 지선, 병점–서동탄 지선, 구로 북쪽(경인선 쪽, HGIS 경인선이 그림), 천안 쪽 지도 밖.
"""

VILLAGE = {"서대문02", "서대문09"}  # 유형 정보가 비어 있지만 마을버스


def main():
    new = json.load(open(f"{B}/bus2026.json"))
    rid = {r["route_no"]: int(r["route_id"]) for r in csv.DictReader(open(f"{RAW}/bus/raw/seoul_bus_routes.csv"))}
    cat = {}
    for y, s in OPEN.items():
        for p in s.split(","):
            p = p.strip()
            if "(폐선)" in p: continue
            cat.setdefault(p, []).append(y)

    def base(n):
        if n.startswith("서울"): return n[:4]
        if n.startswith("급행"): return n
        m = re.match(r"^(N?\d+(?:-\d)?)", n)
        return m.group(1) if m else n

    # 개편 ID 묶음에서 번호 순서가 맞는지
    def k2(n):
        m = re.match(r"^(\d+)", n)
        if not m: return (9, 0)
        s = m.group(1)
        if len(s) == 2: return (0, int(s))
        if len(s) == 3: return (1, int(s))
        if s[0] == "0": return (2, int(s))
        if s[0] == "9": return (4, int(s))
        return (3, int(s))
    blk = sorted((i, n) for n, i in rid.items() if 100100001 <= i <= 100100400)
    pos = {n: j for j, (i, n) in enumerate(blk)}
    def in_order(n):
        j = pos[n]
        prev = [k2(blk[t][1]) for t in range(max(0, j - 2), j)]
        nxt = [k2(blk[t][1]) for t in range(j + 1, min(len(blk), j + 3))]
        return any(p <= k2(n) for p in prev or [(-1, 0)]) and any(k2(n) <= q for q in nxt or [(99, 0)])

    out = {}
    for n in [x["no"] for x in new["nums"] if not x.get("dead")]:
        if n in VILLAGE:
            out[n] = {"oy": None, "kind": "마을", "src": "마을버스라 뺌"}; continue
        if n in CHECKED:
            y, k, note = CHECKED[n]
            out[n] = {"oy": y, "kind": k, "src": "나무위키 노선 문서: " + note}; continue
        i = rid.get(n)
        ys = cat.get(n) or cat.get(base(n))
        if i and 100100001 <= i <= 100100400 and in_order(n) and not (ys and min(ys) > 2004):
            out[n] = {"oy": 2004, "kind": "개편", "src": "노선 ID가 2004년 개편 묶음에 번호 순서대로 있음"}; continue
        if i and 100100001 <= i <= 100100400:
            out[n] = {"oy": 2004, "kind": "계승", "src": "노선 ID가 2004년 개편 묶음에 있으나 번호 순서가 어긋남(번호 변경으로 추정)"}; continue
        if ys:
            y = min(ys)
            out[n] = {"oy": max(y, 2004), "kind": "신설" if y > 2004 else "개편", "src": f"나무위키 분류 {y}년 개업한 버스 노선"}; continue
        out[n] = {"oy": 2026, "kind": "미확인", "src": "신설 연도를 찾지 못함"}
    json.dump(out, open(f"{B}/route_years.json", "w"), ensure_ascii=False, indent=0)
    import collections
    print(collections.Counter(v["kind"] for v in out.values()))
    print("미확인:", [n for n, v in out.items() if v["kind"] == "미확인"])
    print("by year:", sorted(collections.Counter(v["oy"] for v in out.values() if v["oy"]).items()))


if __name__ == "__main__":
    main()
